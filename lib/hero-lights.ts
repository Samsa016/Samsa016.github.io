/** Детерминированный разброс ритма: без него все лампы мигают в такт. */
export function blinkVars(x: number, y: number): Record<string, string> {
  const h = (x * 73856093) ^ (y * 19349663);
  const a = Math.abs(h % 1000) / 1000;
  const b = Math.abs((h >> 10) % 1000) / 1000;
  return {
    "--blink-dur": (0.5 + a * 1.7).toFixed(2) + "s",
    "--blink-delay": (-b * 2.4).toFixed(2) + "s",
  };
}
