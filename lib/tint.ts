import type { CSSProperties } from "react";

/**
 * Переменные цвета работы для инлайн-стиля блока.
 *
 * `--case-lit` — светлая форма тинта. Сырая доминанта постер-кадра почти всегда
 * тёмная и мутная: как заливка она читается грязью, а как свет — не читается
 * вовсе. Поднимаем светлоту в oklab, и тот же цвет начинает работать источником
 * света (решение 31.08.2026, `DESIGN.md` §1).
 *
 * Обе переменные обязаны объявляться в одном месте: var() внутри
 * пользовательского свойства резолвится на элементе, где свойство объявлено.
 * Вынеси `--case-lit` в `:root` — и все работы получат светлую форму
 * заглушечного тинта вместо своей.
 */
export const caseVars = (tint: string): CSSProperties =>
  ({
    "--case-tint": tint,
    "--case-lit": `color-mix(in oklab, ${tint} 62%, white)`,
  }) as CSSProperties;
