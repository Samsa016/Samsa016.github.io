/** Стягивает четырёхугольник к центру на `inset` — зона наведения меньше стекла. */
export function shrink(quad: Quad, inset: number): Quad {
  const cx = quad.reduce((s, p) => s + p[0], 0) / 4;
  const cy = quad.reduce((s, p) => s + p[1], 0) / 4;
  return quad.map(([x, y]) => {
    const dx = x - cx;
    const dy = y - cy;
    const len = Math.hypot(dx, dy) || 1;
    return [x - (dx / len) * inset, y - (dy / len) * inset] as const;
  }) as unknown as Quad;
}

/** Раздвигает четырёхугольник от центра — экран под курсором подаётся вперёд. */
export function expand(quad: Quad, factor: number): Quad {
  const cx = quad.reduce((s, p) => s + p[0], 0) / 4;
  const cy = quad.reduce((s, p) => s + p[1], 0) / 4;
  return quad.map(([x, y]) => [cx + (x - cx) * factor, cy + (y - cy) * factor] as const) as unknown as Quad;
}
